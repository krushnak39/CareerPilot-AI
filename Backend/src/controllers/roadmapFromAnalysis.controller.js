const prisma = require("../config/prisma");

const {
  createActivity,
} = require("../services/activity.service");

const clean = (value, max) =>
  String(value ?? "")
    .trim()
    .slice(0, max);

const capitalize = (text) =>
  text
    ? text.charAt(0).toUpperCase() +
      text.slice(1)
    : text;

// ==========================
// CREATE ROADMAP FROM AI ANALYSIS
// POST /api/learning-roadmaps/from-analysis
// body: { career: string, roadmap: [{ skill, priority,
//         reason, resources[], learning_duration }] }
// ==========================
const createRoadmapFromAnalysis = async (
  req,
  res
) => {
  try {
    const career = clean(
      req.body?.career,
      120
    );

    const steps = Array.isArray(
      req.body?.roadmap
    )
      ? req.body.roadmap.slice(0, 30)
      : [];

    if (!career || steps.length === 0) {
      return res.status(400).json({
        success: false,
        message:
          "career and a non-empty roadmap are required",
      });
    }

    const modules = steps
      .filter((step) => step?.skill)
      .map((step, index) => ({
        title: capitalize(
          clean(step.skill, 120)
        ),
        description: clean(
          `${step.priority || ""} priority • ${
            step.learning_duration || ""
          }. ${step.reason || ""}`,
          500
        ),
        order: index,
        topics: {
          create: (Array.isArray(
            step.resources
          )
            ? step.resources
            : []
          )
            .slice(0, 10)
            .map((resource, topicIndex) => ({
              title: clean(resource, 200),
              order: topicIndex,
            })),
        },
      }));

    const roadmap =
      await prisma.learningRoadmap.create({
        data: {
          userId: req.user.id,
          title: `${career} Roadmap`,
          description:
            "Generated by CareerPilot AI from your resume analysis",
          role: career,
          modules: {
            create: modules,
          },
        },
        include: {
          modules: {
            orderBy: { order: "asc" },
            include: {
              topics: {
                orderBy: { order: "asc" },
              },
            },
          },
        },
      });

    try {
      await createActivity({
        userId: req.user.id,
        type: "ROADMAP_CREATED",
        title: "Learning roadmap created",
        description: roadmap.title,
      });
    } catch (activityError) {
      console.error(
        "Roadmap activity error:",
        activityError.message
      );
    }

    return res.status(201).json({
      success: true,
      message: "Roadmap created successfully",
      data: roadmap,
    });
  } catch (error) {
    console.error(
      "Create Roadmap From Analysis Error:",
      error
    );

    return res.status(500).json({
      success: false,
      message: "Failed to create roadmap",
    });
  }
};

module.exports = {
  createRoadmapFromAnalysis,
};
